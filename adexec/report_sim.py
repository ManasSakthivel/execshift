def render_sim_validation(sv: dict) -> str:
    out = ["# Simulator validation", "",
           "*Generated by `scripts/build_report.py` from `results/simulator_validation.json`. "
           "Do not edit by hand.*", "",
           "This validation was run, and its one failure fixed, **before** any policy was "
           "trained or evaluated. All market data in this project are **synthetic**. Passing "
           "these checks shows that the simulator reproduces a set of well-documented "
           "statistical properties of real markets. It does **not** show that results "
           "obtained in the simulator transfer to a real market. In particular, no simulator "
           "or historical replay can reveal how real participants would have reacted to our "
           "orders.", "",
           "## Nominal parameters and their sources", "",
           "| Quantity | Value | Empirical anchor |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for a, b, c in SIM_PARAMS]
    out += ["", "## Stylised-fact checks", "",
            "Each check compares a statistic of long simulated series (200 series × 2,000 "
            "bins) or of simulated TWAP metaorders against a target range taken from the "
            "cited literature. The ranges were set when the checks were written, before "
            "the results were seen. The one exception is the impact-concavity check, whose "
            "failure is described below.", ""]
    for im in ("sqrt", "linear", "transient"):
        rows = sv[im]
        n_pass = sum(r["status"] == "PASS" for r in rows)
        out += [f"### Impact model: `{im}` ({n_pass}/{len(rows)} PASS)", "",
                "| Check | Value | Target | Status | Source |", "|---|---|---|---|---|"]
        out += [f"| {r['check']} | {r['value']:.4g} | [{r['target_low']:g}, "
                f"{r['target_high']:g}] | {r['status']} | {r['source']} |" for r in rows]
        out.append("")
    k = sv["kurtosis_by_aggregation"]
    out += ["Excess kurtosis by aggregation horizon (sqrt model): "
            f"30 s = {k['1']:.2f}, 5 min = {k['10']:.2f}, 30 min = {k['60']:.2f}.", "",
            "![Simulator validation](../figures/fig1_simulator_validation.png)", "",
            "## A failure we found and fixed", "",
            "The first version of the simulator used **linear** permanent impact (Almgren-Chriss "
            "style) on top of a square-root temporary impact. The metaorder-impact check "
            "measured a log-log slope of cost against participation of **0.87**, against an "
            "empirical 0.5-0.6.",
            "",
            "**Root cause.** The linear permanent component grows in proportion to order size "
            "and dominated the total cost.",
            "",
            "**Fix.** Following the square-root-law literature (Tóth et al. 2011; Donier et al. "
            "2015), cumulative impact was made concave in executed volume, "
            "∝ σ·√(Q/V). The measured slope then became 0.50, with an implied prefactor "
            "Y ≈ 0.7.",
            "",
            "A side effect of the fix: total cumulative-impact cost is invariant to the trading "
            "schedule. Because the agent may only sell, the round-trip manipulation that "
            "Gatheral (2010) rules out for non-decaying nonlinear impact cannot occur. The "
            "`linear` model keeps classic linear permanent impact, matched in cost at 7.5% "
            "participation.",
            "",
            "We also corrected a measurement problem in the check itself. Raw mean IS is "
            "dominated by price noise (SD ≈ 30 bp), so the check now measures impact against a "
            "zero-impact counterfactual on the same episodes (common random numbers).", "",
            "## Properties not modelled (claims are limited accordingly)", ""]
    out += [f"- {x}" for x in sv["not_modelled"]]
    out += ["", "## Consequences for the claims", "",
            "- Policy results are conditional on this parametric market and its three impact "
            "models. They are evidence about *mechanisms*, such as how uncertainty relates to "
            "regret under shift, not about the size of gains on any real venue.",
            "- The alpha signal is a stylised order-flow predictor with R² ≈ 1.3% at 30 s. "
            "Its existence and strength are assumptions, and the in-distribution RL edge "
            "depends on it.",
            "- Seasonality, the leverage effect and long memory are absent. Strategies that "
            "would exploit or suffer from them are not tested.", ""]
    return "\n".join(out)


def render_baselines(bl: dict) -> str:
    out = ["# Baselines", "",
           "*Generated by `scripts/build_report.py` from `results/baselines_*.json`. Do not edit "
           "by hand.*", "",
           "Every baseline is newly implemented in `adexec/policies.py`; none is inherited "
           "from the upstream repository. Tuning used only the 4,000 in-distribution "
           "episodes of the TRAIN split (split tag 11). That is the same in-distribution "
           "information the RL agent is trained on; neither saw a shifted market. All "
           "candidates were scored on identical episodes (common random numbers).", "",
           "| Policy | Form | Tuned parameters | Grid / budget |", "|---|---|---|---|",
           "| TWAP (fallback) | sell remaining / steps left | none | — |",
           "| AC | static Almgren-Chriss sinh trajectory (κ<0: mirrored back-loading) | κ | "
           "25-point grid on [−3, 3] |",
           "| ADAPT | TWAP-remaining × exp(−a·signal + b·depth − c·spread − d·rv + e·volume), "
           "clipped to [¼, 4] | a, b, c, d, e | coordinate descent, 3 rounds, 25-point grid "
           "on [−3, 3] per weight (≤ 361 evaluations) |",
           "| A3 blend | w·RL + (1−w)·TWAP per step | w | {0.25, 0.5, 0.75} on validation "
           "(LOFO) |",
           "| A9 rule gate | fall back if rv, spread or size > TRAIN-ID q-quantile, or depth "
           "or volume < (1−q)-quantile | q | {0.80, 0.90, 0.95, 0.99} on validation (LOFO) |",
           "| A10 random | fall back with RCG's per-condition, per-replicate rate | none "
           "(matched) | exact expectation |", "",
           "## Tuned values", "", "| Impact model | AC κ | AC train IS (bp) | TWAP train IS "
           "(bp) | ADAPT weights (a, b, c, d, e) | ADAPT train IS (bp) | ADAPT evaluations |",
           "|---|---|---|---|---|---|---|"]
    for im, r in bl.items():
        out.append(f"| {im} | {r['AC']['kappa']:g} | {r['AC']['train_mean_IS']:.3f} | "
                   f"{r['AC']['grid']['0.0']:.3f} | {tuple(r['ADAPT']['weights'])} | "
                   f"{r['ADAPT']['train_mean_IS']:.3f} | {r['ADAPT']['evaluations']} |")
    out += ["", "Under the risk-neutral IS objective, tuned AC is practically identical to "
            "TWAP: train IS differs by about 0.01 bp. This is what theory predicts. With "
            "zero risk aversion the Almgren-Chriss optimum is the uniform schedule, and the "
            "small selected κ ≠ 0 reflects noise in the selection. We keep AC in every table "
            "for completeness, but the meaningful classical baselines are TWAP (static, "
            "robust) and ADAPT (feature-driven, strong).",
            "",
            "**Grid-edge check.** The first ADAPT grid ([−1, 1]) put the signal weight on its "
            "boundary, and so did a second ([−2, 2]) under the transient model. To avoid "
            "handicapping the baseline, the grid was widened to [−3, 3] before any RL policy "
            "was evaluated. All selected weights are now interior.", ""]
    return "\n".join(out)
